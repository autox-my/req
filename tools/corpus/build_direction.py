def compound_pairs(text: str, families=None, single=None):
    """[(code, out, first_label, second_label, label)] for every compound that applies to `text`.

    Both mutations are applied in order (the second to the first's output) and the pair keeps only if
    each changed the text. The families with a bound need `single_bound`; the guard-and-bound families
    are for obligations stated with SHALL (a binding modality: ADR 0041 gives the guard an effect).
    `families` and `single` default to the v3 table and predicate; the PURE path (v4) passes its own.
    """
    families = COMPOUNDS if families is None else families
    single = single_bound if single is None else single
    if not _negation_free(text):
        return []
    found = []
    for code, (l1, f1), (l2, f2), needs in families:
        if needs in ("bound", "binding") and not single(text):
            continue
        if needs == "binding" and not re.search(r"\bshall\b", text, re.I):
            continue
        # The first mutation must act on the source text itself, the second on its result.
        mid = f1(text)
        if not mid or mid == text:
            continue
        out = f2(mid)
        if not out or out == mid:
            continue
        found.append((code, out, l1, l2, compound_label(l1, l2)))
    return found


def prohibition_base(text: str):
    """(statement, synthesised) of a prohibition carrying one bound, or None.

    A source statement that already says "shall not" is used as it stands. The pinned sources hold few
    of those with a bound (the generator counts them), so a source "shall" statement is flipped to
    "shall not" to give the swapped-sense families something to measure — the flipped text is the
    *base* of the pair, and both sides keep the prohibition; the label is the numeric mutation's.
    """
    if not single_bound(text):
        return None
    if is_prohibition(text):
        return text, False
    if not _negation_free(text):
        return None
    flipped = d_polarity_flip(text)
    if flipped and is_prohibition(flipped) and single_bound(flipped):
        return flipped, True
    return None


def mirror_compound(pair, components):
    """The compound pair swapped, labelled by the rule from the two opposite labels."""
    pid, a, b, src, _label, note = pair
    l1, l2, binding = components[pid]
    o1, o2 = OPPOSITE_V3[l1], OPPOSITE_V3[l2]
    # A mirrored pair reads the mutations backwards in the same axis order.
    return (pid + "r", b, a, src, compound_label(o1, o2, binding),
            f"mirror of {pid} (a and b swapped): {note}"), (o1, o2, binding)


