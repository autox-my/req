#!/usr/bin/env python3
"""Build the **direction gold set**: what kind of change is this?

Labels are the mutation applied — never the classifier's answer. Same discipline as the
identity corpora, for the same reason: a corpus labelled by the thing it tests cannot
falsify it. Sources are the same three real-requirement repositories, pinned by commit,
fetched through `build_external` so there is one fetcher, not two.

Usage: python3 tools/corpus/build_direction.py > bench/corpus/direction-v1.yml
       python3 tools/corpus/build_direction.py --version 2 > bench/corpus/direction-v2.yml
       python3 tools/corpus/build_direction.py --version 3 > bench/corpus/direction-v3.yml
       python3 tools/corpus/build_direction.py --version 4 --pure-zip requirements.zip > bench/corpus/direction-v4.yml
       python3 tools/corpus/build_direction.py --self-check    # the pure half; no network

Version 2 (S-1, ADR 0040 decision 5) is every v1 pair plus the **mirrors** of the loosening/tightening
families (the pair swapped, labelled with the opposite class — the label is still the mutation, read
backwards) and the **membership** mutations on any source statement carrying an enumeration. It exists to
measure false carries with a support large enough to mean something: v1 holds 5 modality_strengthening and
9 numeric_tightening pairs, so "zero false carries" out of that is vacuous. Both versions read the same
pinned commits (`V4_PINS`), so v1 regenerates byte-identical and v2 differs only by the added pairs.

Version 3 (R-2, ADR 0044 decision 7) is every v2 pair plus the two families v1/v2 never held, because
each of their pairs carries exactly one mutation: **compound** pairs (two mutations on one statement,
labelled by the rule of decisions 3-4 from the two mutations' own labels, never from the classifier)
and **numeric mutations on a prohibition** (labelled with the swapped sense, decision 5). v1 and v2
are regenerated byte-identical: nothing below changes what versions 1 and 2 emit.

Version 4 (G-1) is every v3 pair plus pairs built from the numeric statements of **PURE** (Ferrari, Spagnolo,
Gnesi, "PURE: A Dataset of Public Requirements Documents", RE 2017; Zenodo 10.5281/zenodo.1414117; CC BY 4.0),
read from the record's `requirements.zip` through `pdftotext` (poppler, the pinned version below) by the
families and mutations already above. It exists for support: ADR 0040 admits a class on its false-carry support,
and `numeric_loosening` has 9 at v2. PURE holds no `one of` enumeration, so `membership_widening` stays at 0 and
none is synthesised. The archive and the extractor are pinned and checked **before** anything is fetched or run;
v1-v3 are regenerated byte-identical (nothing in the PURE path touches what they emit).
"""
