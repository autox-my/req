# The label of the same change read backwards. A pair swapped is the opposite mutation, so the label
# comes from this table (the mutation), never from the classifier.
OPPOSITE = {
    "modality_weakening": "modality_strengthening",
    "numeric_loosening": "numeric_tightening",
    "numeric_tightening": "numeric_loosening",
    "membership_narrowing": "membership_widening",
    "membership_widening": "membership_narrowing",
}


def mirror(pair):
    """(id, a, b, src, label, note) -> its mirror, or None when the label has no opposite."""
    pid, a, b, src, label, note = pair
    if label not in OPPOSITE:
        return None
    return (pid + "r", b, a, src, OPPOSITE[label], f"mirror of {pid} (a and b swapped): {note}")


# ---------------------------------------------------------------------------------------------------
# v3 (R-2, ADR 0044 decision 7): compound pairs and numeric mutations on a prohibition.
#
# The label of a compound pair is `compound_label` applied to the two mutations' labels — the rule of
# decisions 3-4, written here from the ADR and from English, never read off the classifier. The sense of
# a numeric mutation on a prohibition is the swapped one (decision 5): the bound of a SHALL NOT is the
# region that is *forbidden*, so a change that would loosen an obligation's bound tightens it.
# ---------------------------------------------------------------------------------------------------

# What a single mutation does to what complies: +1 permits more, -1 permits less.
EFFECT = {"modality_weakening": 1, "numeric_loosening": 1, "membership_widening": 1,
          "modality_strengthening": -1, "numeric_tightening": -1, "membership_narrowing": -1}
SCOPE = ("scope_narrowing", "scope_widening")
OPPOSITE_V3 = {**OPPOSITE, "modality_strengthening": "modality_weakening",
               "scope_narrowing": "scope_widening", "scope_widening": "scope_narrowing"}


def compound_label(first: str, second: str, binding: bool = True) -> str:
    """The label of a statement that carries two mutations, `first` before `second` in the axis order
    (modality, conditions, bound). ADR 0044 decision 4: a scope axis moving together with the modality
    has no direction. Decision 3: otherwise a direction only if both agree, named by the first.
    A guard on an obligation permits more when added and less when removed (ADR 0041); on a permission
    (`binding` false) it has no effect."""
    if any(l in SCOPE for l in (first, second)) and any(l.startswith("modality_") for l in (first, second)):
        return "scope_divergence"

    def effect(label: str) -> int:
        if label == "scope_narrowing":
            return 1 if binding else 0
        if label == "scope_widening":
            return -1 if binding else 0
        return EFFECT.get(label, 0)

    e1, e2 = effect(first), effect(second)
    return first if e1 != 0 and e1 == e2 else "scope_divergence"


def _negation_free(s: str) -> bool:
    """No other negation in the statement: a "not", "never" or "no" would make the bound a different
    sense than the label says, and the polarity-sensitive families would be labelled wrongly."""
    return not re.search(r"\b(not|never|no|none|cannot)\b|n't", s, re.I)


def single_bound(s: str) -> bool:
    """One sentence, one quantity, and a comparator phrase: the number the mutation moves is the
    bound the phrase names. Multi-sentence statements are skipped, not guessed at."""
    body = s.strip().rstrip(".")
    if re.search(r"[.!?]\s+\S", body):
        return False
    return len(re.findall(rf"\b{NUMBER_UNIT}\b", s)) == 1 and bound_side(s) is not None


def is_prohibition(s: str) -> bool:
    return bool(re.search(r"\bshall not\b", s, re.I))


def d_prohibition_loosening(s: str):
    """A bound moved so that the prohibition forbids less (the swapped sense of a numeric loosening)."""
    side = bound_side(s)
    if side == "upper":
        return _scale(s, Decimal("0.8"))
    if side == "lower":
        return _scale(s, Decimal("1.25"))
    return None


def d_prohibition_tightening(s: str):
    """A bound moved so that the prohibition forbids more (the swapped sense of a numeric tightening)."""
    side = bound_side(s)
    if side == "upper":
        return _scale(s, Decimal("1.25"))
    if side == "lower":
        return _scale(s, Decimal("0.8"))
    return None


def d_modality_strengthening_v3(s: str):
    """SHOULD -> SHALL, or MAY -> SHALL: the obligation strengthened.

    v1's strengthening is MAY -> SHALL only, and the pinned sources hold no bounded statement that says
    "may", so the compound families with a strengthened modality would be empty. SHOULD is rank 2 and
    SHALL rank 3 (ADR 0026 §2), so the label is the same. Used by the compound families only: v1 and v2
    keep `d_modality_strengthening` and regenerate byte-identically.
    """
    out = d_modality_strengthening(s)
    if out:
        return out
    if re.search(r"\bshould\b", s, re.I):
        return re.sub(r"\bshould\b", "shall", s, count=1, flags=re.I)
    return None


# (code, mutation function, label). Every compound is `first` then `second`, in axis order.
